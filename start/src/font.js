// Global font cache
let currentFontStyle = 'normal';
let botNumber = null;

// Function to update font from DB
async function updateFont() {
    try {
        if (botNumber) {
            const newFont = await db.get(botNumber, 'bot_font', 'normal');
            if (newFont !== currentFontStyle) {
                currentFontStyle = newFont;
                console.log(`🎨 Font updated to: ${currentFontStyle}`);
            }
        }
    } catch (error) {
        // Silent fail
    }
}

// Start auto-update
setInterval(updateFont, 5000);

// Function to set bot number (call this once when bot starts)
function setBotNumber(number) {
    botNumber = number;
    updateFont(); // Initial load
}

// Function to apply font to text
function applyFont(text) {
    if (!text || currentFontStyle === 'normal') return text;
    const map = fontMaps[currentFontStyle];
    if (!map) return text;
    return text.split('').map(char => map[char] || char).join('');
}

